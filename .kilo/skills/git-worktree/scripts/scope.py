#!/usr/bin/env python3
"""The scope pointer that a work-surface repository carries.

A work surface is a repository the factory builds in: an application, a
microservice, a scope folder. It holds application code and nothing else.
The rules that govern the work, the documentation that describes it, the
board that tracks it and the harness that builds it all live in the project
repository, which is the control repo for that work.

Each work surface therefore carries one generated file, ``AGENTS.md``, that
points at the project. It is:

- **never committed.** The file is listed in the repository's local exclude
  file, ``.git/info/exclude``, which belongs to the clone, is shared by every
  worktree of that repository, and is never part of a commit.
- **regenerated.** ``guard.py sync`` writes it from this template, so the
  pointer can never drift from the project it names.

Nothing in the work surface is a second copy of the project's rules. The
canonical scope rules live in the project's ``.kilo/scopes/``, and the
per-unit documentation lives in the project's ``docs/handover/``.
"""
import os

POINTER_MARKER = "<!-- generated by guard.py sync; do not edit, do not commit -->"

POINTER_TEMPLATE = """# AGENTS.md — {repo}

{marker}

This repository is a **work surface** of the project at `{project}`.
It holds application code only. The rules that govern the work, the
documentation that describes it and the board that tracks it all live in the
project. This file points at them.

| What | Where |
|---|---|
| The rules every agent follows | `{project}/AGENTS.md` |
| The scope rules for this repository | `{scope}` |
| This unit's documentation | `{unit_doc}` |
| The work board | `{board}` |
| The decisions behind the design | `{decisions}` |
| The harness: skills, guards, commands | `{project}/.kilo/` |

Read `{scope}` and `{project}/AGENTS.md` before you start.
Work only inside this repository.
"""

DEFAULT_SCOPE = "service"
IGNORED_NAME = "AGENTS.md"
IGNORED_PATTERNS = ["AGENTS.md", ".kilo/", "kilo.jsonc"]


def scope_file(control, unit_id):
    """The canonical scope-rules file for this unit, or None."""
    scopes_dir = os.path.join(control, ".kilo", "scopes")
    candidate = os.path.join(scopes_dir, unit_id + ".md")
    if os.path.exists(candidate):
        return candidate
    fallback = os.path.join(scopes_dir, DEFAULT_SCOPE + ".md")
    return fallback if os.path.exists(fallback) else None


def _relative(destination_dir, path):
    """The path written from the point of view of the file that carries it."""
    return os.path.relpath(path, destination_dir).replace(os.sep, "/")


def pointer_content(control, unit_id, destination_dir):
    """The text of this unit's pointer, or None when there is no scope."""
    scope = scope_file(control, unit_id)
    if not scope:
        return None
    unit_doc = os.path.join(control, "docs", "handover", unit_id + ".md")
    if not os.path.exists(unit_doc):
        unit_doc = "not written yet"
    project = _relative(destination_dir, control)
    return POINTER_TEMPLATE.format(
        repo=unit_id,
        marker=POINTER_MARKER,
        project=project,
        scope=_relative(destination_dir, scope),
        unit_doc=_relative(destination_dir, unit_doc),
        board=_relative(destination_dir, os.path.join(control, "docs", "BOARD.md")),
        decisions=_relative(destination_dir,
                            os.path.join(control, "docs", "DECISIONS.md")),
    )


def read_existing(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        return None


def write_pointer(destination_dir, content):
    """Write the pointer into a work surface.

    Returns (state, message). The state is one of:

    - ``written``    the pointer was created
    - ``refreshed``  the pointer was regenerated
    - ``unchanged``  the pointer was already current
    - ``kept``       a hand-written file is there; it is left alone
    """
    path = os.path.join(destination_dir, IGNORED_NAME)
    existing = read_existing(path)
    if existing is not None and POINTER_MARKER not in existing:
        return "kept", "a hand-written AGENTS.md is there; left alone"
    if existing == content:
        return "unchanged", "already current"
    os.makedirs(destination_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    return ("written" if existing is None else "refreshed"), path


def exclude_file(repo):
    """The repository's local exclude file, or None when it is not a repository."""
    git_dir = os.path.join(repo, ".git")
    if not os.path.isdir(git_dir):
        return None
    return os.path.join(git_dir, "info", "exclude")


def ensure_ignored(repo):
    """Keep the generated files out of every commit in this repository.

    The rules go in ``.git/info/exclude``: it belongs to the clone, it is
    shared by every worktree of the repository, and it is never committed.
    Returns (ok, message).
    """
    path = exclude_file(repo)
    if not path:
        return False, "not a git repository; nothing to exclude"
    existing = read_existing(path) or ""
    patterns = [line.strip() for line in existing.splitlines()]
    missing = [p for p in IGNORED_PATTERNS if p not in patterns]
    if not missing:
        return True, "already excluded"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "a", encoding="utf-8") as fh:
        if existing and not existing.endswith("\n"):
            fh.write("\n")
        fh.write("\n# generated by the factory; never committed\n")
        for pattern in missing:
            fh.write("%s\n" % pattern)
    return True, path
